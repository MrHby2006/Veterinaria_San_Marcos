function verDetalle(código){
    let medicamentoSeleccionado;

    for (let i = 0; i < medicamentos.length; i++){
        if (medicamentos[i].código === código){
            medicamentoSeleccionado = medicamentos[i];
            break;
        }
    }

    localStorage.setItem(
        "medicamento",
        JSON.stringify(medicamentoSeleccionado)
    );

    window.location.href = "detalle.html";
}